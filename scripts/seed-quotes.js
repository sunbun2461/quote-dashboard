async function seed() {
  console.log('Connecting to Supabase...')
  console.log('URL:', supabaseUrl)

  // Insert quotes
  console.log('\nInserting 25 quotes...')
  const { data, error } = await supabase
    .from('quotes')
    .insert(quotes)
    .select()

  if (error) {
    console.error('Error inserting quotes:', error.message)
    console.error('Details:', error.details)
    console.error('Hint:', error.hint)
    process.exit(1)
  }

  console.log(`Successfully inserted ${data.length} quotes!`)
  console.log('\nSample of inserted data:')
  console.log(data.slice(0, 3).map(q => `  - ${q.quote_number}: ${q.customer_name} (${q.quote_type})`).join('\n'))
}

